async (page) => {
  await page.reload();
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'Chọn người và tổ chức · mẫu 2 trường · nháp v1',exact:true}).click();
  await page.getByRole('combobox',{name:'Nhóm thuộc tính',exact:true}).click();
  await page.getByRole('option',{name:'Dữ liệu',exact:true}).click();
  await page.getByRole('combobox',{name:'Nguồn dữ liệu',exact:true}).click();
  if(await page.getByRole('option',{name:'Phòng ban · dữ liệu mẫu',exact:true}).count()) throw Error('Department source offered for person');
  if(await page.getByRole('option',{name:'Công ty · dữ liệu mẫu',exact:true}).count()) throw Error('Company source offered for person');
  await page.getByRole('option',{name:'Người trong tổ chức',exact:true}).click();
  await page.getByRole('combobox',{name:'Giá trị mặc định',exact:true}).click();
  await page.getByRole('option',{name:'Người đang tạo biểu mẫu',exact:true}).click();
  const allow=()=>page.getByRole('checkbox',{name:'Cho phép đổi người',exact:true});
  await allow().check();
  const requester=()=>page.getByRole('combobox',{name:'Người yêu cầu (bắt buộc)',exact:true});
  await requester().click();
  await page.getByRole('option',{name:/^An Demo/}).click();
  if(!(await requester().innerText()).includes('An Demo')) throw Error('Canvas did not retain changed person');
  await requester().click();
  await page.getByRole('textbox',{name:'Tìm tên, email hoặc phòng ban...',exact:true}).fill('Bình');
  await page.getByRole('option',{name:/^Bình Demo/}).click();
  if(!(await requester().innerText()).includes('Bình Demo')) throw Error('Canvas search selection failed');
  await allow().uncheck();
  if(!(await requester().isDisabled())) throw Error('Canvas did not lock');
  await allow().check();
  await page.screenshot({animations:'disabled',path:'output/playwright/forms-person-change-1440-vi-light.png'});
  await page.getByRole('tab',{name:'Xem thử biểu mẫu',exact:true}).click();
  await requester().click();
  await page.getByRole('option',{name:/^An Demo/}).click();
  if(!(await requester().innerText()).includes('An Demo')) throw Error('Preview did not retain changed person');
  await page.getByRole('tab',{name:'Thiết kế trường',exact:true}).click();
  await page.setViewportSize({width:1366,height:768});
  await page.getByRole('button',{name:'Bật giao diện tối',exact:true}).click();
  await page.getByRole('combobox',{name:'Ngôn ngữ: Tiếng Việt',exact:true}).click();
  await page.getByRole('option',{name:'English',exact:true}).click();
  await page.getByRole('combobox',{name:'Data source',exact:true}).click();
  if(await page.getByRole('option',{name:'Departments · demo data',exact:true}).count()) throw Error('English source filter failed');
  await page.keyboard.press('Escape');
  await page.screenshot({animations:'disabled',path:'output/playwright/forms-person-change-1366-en-dark.png'});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('tab',{name:'Field properties',exact:true}).click();
  await page.getByRole('combobox',{name:'Data source',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({animations:'disabled',path:'output/playwright/forms-person-change-390-en-dark.png'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('Mobile overflow');
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
  await page.getByRole('combobox',{name:'Language: English',exact:true}).click();
  await page.getByRole('option',{name:'Tiếng Việt',exact:true}).click();
  await page.getByRole('button',{name:'Danh sách biểu mẫu',exact:true}).click();
  await page.getByRole('button',{name:'Đề nghị mua sắm · mẫu 3 trường · nháp v1',exact:true}).click();
  await page.getByRole('button',{name:'Bỏ thay đổi và tiếp tục',exact:true}).click();
  return {result:'PASS',saved:false,checks:['compatible source filtering','creator default changed twice on canvas','canvas lock and unlock','changed person in Preview','VI EN light dark desktop mobile']};
}
